function serialize(name, obj) {
  const lines = Object.entries(obj)
    .map(([k, v]) => `  "${k}": ${JSON.stringify(v)},`)
    .join("\n");
  return `export const ${name}: Record<string, string> = {\n${lines}\n};\n`;
}

